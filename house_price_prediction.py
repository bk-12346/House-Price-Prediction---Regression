# House Price Prediction Model using Regression

# import necessary librararies
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

#1. import dataset from Kaggle
import kagglehub

# Download latest version
path = kagglehub.dataset_download("rishitaverma02/house-prices-advanced-regression-techniques")

print("Path to dataset files:", path)

# 1. load data to dataframe and load target data to target variable
train_df = pd.read_csv(path + "/train (1).csv")
test_df = pd.read_csv(path + "/test (1).csv")

train_df.head()

test_df.head()

# describe the dataset
train_df.describe()

# check for missing values
train_df.isnull().sum()

# missing values identified; imputing them

# Impute numerical columns with the mean
train_df.fillna(train_df.select_dtypes(include=np.number).mean(), inplace=True)
test_df.fillna(test_df.select_dtypes(include=np.number).mean(), inplace=True)

# Impute categorical columns with the mode
for col in train_df.select_dtypes(include='object').columns:
    train_df[col].fillna(train_df[col].mode()[0], inplace=True)
for col in test_df.select_dtypes(include='object').columns:
    test_df[col].fillna(test_df[col].mode()[0], inplace=True)

# Select categorical columns
categorical_cols_train = train_df.select_dtypes(include='object').columns
categorical_cols_test = test_df.select_dtypes(include='object').columns

# Apply one-hot encoding to training and testing dataframes
train_df_encoded = pd.get_dummies(train_df, columns=categorical_cols_train, dummy_na=False)
test_df_encoded = pd.get_dummies(test_df, columns=categorical_cols_test, dummy_na=False)

# Display the first few rows of the encoded training dataframe
display(train_df_encoded.head())

# Separate features (X) and target (y)
X = train_df_encoded.drop('SalePrice', axis=1)

# Get the target variable from the training data and apply log transformation
y = np.log(train_df_encoded['SalePrice'])

# Align columns between the training and testing datasets - this is important after one-hot encoding
# This will add missing columns to the test set and fill with 0, and drop columns not in the training set
X_train, X_test = X.align(test_df_encoded, join='inner', axis=1, fill_value=0)

# Display the shapes of the prepared data
print("Shape of X_train:", X_train.shape)
print("Shape of y:", y.shape)
print("Shape of X_test:", X_test.shape)

"""## Train and evaluate a linear regression model

Train a linear regression model on the training data and evaluate its performance using metrics like RMSE and R-squared.
"""

from sklearn.linear_model import LinearRegression
from sklearn.model_selection import train_test_split
from sklearn.metrics import mean_squared_error, r2_score

# Initialize and train the Linear Regression model
model = LinearRegression()
model.fit(X_train, y)

# Make predictions on the training data to evaluate the model
y_train_pred = model.predict(X_train)

# Evaluate the model's performance on the training data
rmse_train = np.sqrt(mean_squared_error(y, y_train_pred))
r2_train = r2_score(y, y_train_pred)

print(f"Linear Regression Model Performance on Training Data:")
print(f"RMSE: {rmse_train}")
print(f"R-squared: {r2_train}")

"""## Train and evaluate a regularized model

Train a Ridge or Lasso regression model on the training data and evaluate its performance using metrics like RMSE and R-squared.
"""

from sklearn.linear_model import Ridge
from sklearn.metrics import mean_squared_error, r2_score

# Initialize and train the Ridge model
ridge_model = Ridge(alpha=1.0)
ridge_model.fit(X_train, y)

# Make predictions on the training data
y_train_pred_ridge = ridge_model.predict(X_train)

# Evaluate the model's performance on the training data
rmse_train_ridge = np.sqrt(mean_squared_error(y, y_train_pred_ridge))
r2_train_ridge = r2_score(y, y_train_pred_ridge)

print(f"Ridge Regression Model Performance on Training Data:")
print(f"RMSE: {rmse_train_ridge}")
print(f"R-squared: {r2_train_ridge}")

"""## Train and evaluate a randomforest regressor

Train a RandomForest Regressor model on the training data and evaluate its performance using metrics like RMSE and R-squared.

"""

from sklearn.ensemble import RandomForestRegressor

# Initialize a RandomForestRegressor model
rf_model = RandomForestRegressor(random_state=42) # Add random_state for reproducibility

# Train the RandomForestRegressor model
rf_model.fit(X_train, y)

# Make predictions on the training data
y_train_pred_rf = rf_model.predict(X_train)

# Calculate RMSE for the RandomForest Regressor model
rmse_train_rf = np.sqrt(mean_squared_error(y, y_train_pred_rf))

# Calculate R-squared for the RandomForest Regressor model
r2_train_rf = r2_score(y, y_train_pred_rf)

# Print the performance metrics
print(f"RandomForest Regressor Model Performance on Training Data:")
print(f"RMSE: {rmse_train_rf}")
print(f"R-squared: {r2_train_rf}")

"""## Compare model performance

Compare the performance metrics of the Linear Regression model, the regularized model, and the RandomForest Regressor to determine which model performed best on the training data.

"""

print("Linear Regression Model Performance on Training Data:")
print(f"RMSE: {rmse_train}")
print(f"R-squared: {r2_train}")
print("\nRidge Regression Model Performance on Training Data:")
print(f"RMSE: {rmse_train_ridge}")
print(f"R-squared: {r2_train_ridge}")
print("\nRandomForest Regressor Model Performance on Training Data:")
print(f"RMSE: {rmse_train_rf}")
print(f"R-squared: {r2_train_rf}")

# Create a DataFrame to hold the performance metrics
performance_data = {
    'Model': ['Linear Regression', 'Ridge Regression', 'RandomForest Regressor'],
    'RMSE': [rmse_train, rmse_train_ridge, rmse_train_rf],
    'R-squared': [r2_train, r2_train_ridge, r2_train_rf]
}
performance_df = pd.DataFrame(performance_data)

# Melt the DataFrame for easier plotting with seaborn
performance_df_melted = performance_df.melt('Model', var_name='Metric', value_name='Score')

# Create bar plots for RMSE and R-squared
plt.figure(figsize=(12, 6))

plt.subplot(1, 2, 1)
sns.barplot(x='Model', y='Score', data=performance_df_melted[performance_df_melted['Metric'] == 'RMSE'])
plt.title('Model Comparison - RMSE')
plt.ylabel('RMSE')
plt.xticks(rotation=45, ha='right')

plt.subplot(1, 2, 2)
sns.barplot(x='Model', y='Score', data=performance_df_melted[performance_df_melted['Metric'] == 'R-squared'])
plt.title('Model Comparison - R-squared')
plt.ylabel('R-squared')
plt.xticks(rotation=45, ha='right')

plt.tight_layout()
plt.show()

from sklearn.model_selection import cross_val_score

# Perform cross-validation for Linear Regression
rmse_cv_lr = -cross_val_score(model, X_train, y, scoring='neg_mean_squared_error', cv=5)
rmse_cv_lr = np.sqrt(rmse_cv_lr)
print(f"Linear Regression Cross-Validation RMSE (5-fold): {rmse_cv_lr.mean():.4f} (+/- {rmse_cv_lr.std():.4f})")

# Perform cross-validation for Ridge Regression
rmse_cv_ridge = -cross_val_score(ridge_model, X_train, y, scoring='neg_mean_squared_error', cv=5)
rmse_cv_ridge = np.sqrt(rmse_cv_ridge)
print(f"Ridge Regression Cross-Validation RMSE (5-fold): {rmse_cv_ridge.mean():.4f} (+/- {rmse_cv_ridge.std():.4f})")

# Perform cross-validation for RandomForest Regressor
rmse_cv_rf = -cross_val_score(rf_model, X_train, y, scoring='neg_mean_squared_error', cv=5)
rmse_cv_rf = np.sqrt(rmse_cv_rf)
print(f"RandomForest Regressor Cross-Validation RMSE (5-fold): {rmse_cv_rf.mean():.4f} (+/- {rmse_cv_rf.std():.4f})")

print("Model Performance Comparison:")
print("-" * 30)

print("Linear Regression:")
print(f"  Training RMSE: {rmse_train:.4f}")
print(f"  Cross-Validation RMSE (mean): {rmse_cv_lr.mean():.4f}")
print(f"  Cross-Validation RMSE (std): {rmse_cv_lr.std():.4f}")

print("\nRidge Regression:")
print(f"  Training RMSE: {rmse_train_ridge:.4f}")
print(f"  Cross-Validation RMSE (mean): {rmse_cv_ridge.mean():.4f}")
print(f"  Cross-Validation RMSE (std): {rmse_cv_ridge.std():.4f}")

print("\nRandomForest Regressor:")
print(f"  Training RMSE: {rmse_train_rf:.4f}")
print(f"  Cross-Validation RMSE (mean): {rmse_cv_rf.mean():.4f}")
print(f"  Cross-Validation RMSE (std): {rmse_cv_rf.std():.4f}")

# Make predictions on the test data using the trained models

# Linear Regression predictions
y_test_pred_lr = model.predict(X_test)

# Ridge Regression predictions
y_test_pred_ridge = ridge_model.predict(X_test)

# RandomForest Regressor predictions
y_test_pred_rf = rf_model.predict(X_test)

